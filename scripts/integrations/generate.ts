/**
 * Generates only the typed assembly references that are still missing for one adapter.
 *
 * It never writes a native implementation, a no-op, a throwing body, a declaration-only stub or an
 * empty implementation module. Missing implementation factories are imported from a deliberately
 * absent module: the generated assembly must fail TypeScript checking until a human or agent
 * supplies those exports. The generator does not rewrite an existing native implementation to
 * fabricate a delivery callback; that case is reported as an actionable limitation.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import ts from "typescript-compiler";
import type {
	ContractSupply,
	GeneratedFile,
	GenerationOptions,
	GenerationResult,
	IntegrationContract,
	IntegrationDiagnostic,
} from "./model";
import {
	evaluatePortSupply,
	inspectAdapterSource,
	inspectDeliveryMemberGaps,
	projectDeliveryContract,
	projectFrameworkContract,
	projectPortDelivery,
	type AdapterBindingEntry,
	type AdapterInspection,
	type DeliveryMemberGap,
	type DeliveryProjection,
} from "./supply";

const MISSING_IMPLEMENTATION_MODULE = "missing-implementations";
const GENERATED_HEADER = "// Generated by scripts/integrations/generate.ts.";

interface GenerationDiagnosticInput {
	readonly code: string;
	readonly file: string;
	readonly line: number;
	readonly column: number;
	readonly message: string;
	readonly suggestion: string;
}

interface TextEdit {
	readonly start: number;
	readonly end: number;
	readonly text: string;
}

interface TargetMember {
	readonly member: string;
	readonly replace: boolean;
}

interface ContractWork {
	readonly contract: IntegrationContract;
	readonly supply: ContractSupply;
	readonly portMember?: string;
	readonly projections?: readonly DeliveryProjection[];
	readonly include: boolean;
}

function addDiagnostic(
	root: string,
	adapterDir: string,
	diagnostics: IntegrationDiagnostic[],
	keys: Set<string>,
	input: GenerationDiagnosticInput,
): void {
	const key = `${input.code}|${input.file}|${input.line}|${input.column}|${input.message}`;
	if (keys.has(key)) return;
	keys.add(key);
	diagnostics.push({
		file: input.file.startsWith(root) ? relativeFile(root, input.file) : input.file,
		line: input.line,
		column: input.column,
		code: input.code,
		message: input.message,
		suggestion: input.suggestion,
	});
}

function relativeFile(root: string, file: string): string {
	return path.relative(root, file).split(path.sep).join("/");
}

function diagnosticAtAdapter(
	root: string,
	adapterDir: string,
	diagnostics: IntegrationDiagnostic[],
	keys: Set<string>,
	code: string,
	message: string,
	suggestion: string,
): void {
	addDiagnostic(root, adapterDir, diagnostics, keys, {
		code,
		file: adapterDir,
		line: 1,
		column: 1,
		message,
		suggestion,
	});
}

function pascalCase(value: string): string {
	const parts = value.split(/[^A-Za-z0-9]+/).filter(part => part.length > 0);
	const joined = parts.map(part => `${part[0]?.toUpperCase() ?? ""}${part.slice(1)}`).join("");
	return /^[A-Za-z_]/.test(joined) ? joined : `A${joined}`;
}

function portConstantName(adapter: string): string {
	const upper = adapter.toUpperCase().replace(/[^A-Z0-9]+/g, "_").replace(/^_+|_+$/g, "");
	return `${/^[A-Z_]/.test(upper) ? upper : `A${upper}`}_PORT`;
}

function moduleSpecifier(fromFile: string, toFile: string): string {
	let relative = path.relative(path.dirname(fromFile), toFile).split(path.sep).join("/");
	if (!relative.startsWith(".")) relative = `./${relative}`;
	return relative;
}

function factoryNameFor(member: string): string {
	return `create${pascalCase(member)}`;
}

function deliveryExportName(gap: DeliveryMemberGap): string {
	return `missing${pascalCase(gap.kind)}${pascalCase(gap.member)}`;
}

function deliveryContractName(gap: DeliveryMemberGap): string {
	return `Missing${pascalCase(gap.kind)}${pascalCase(gap.member)}`;
}

function deliveryContractType(gap: DeliveryMemberGap): string {
	return `AdapterDeliveryMap[${JSON.stringify(gap.kind)}][${JSON.stringify(gap.member)}]`;
}

function generatedImportModule(specifier: string): boolean {
	const normalized = specifier.split("\\").join("/");
	return normalized.slice(normalized.lastIndexOf("/") + 1) === MISSING_IMPLEMENTATION_MODULE;
}

function collectIdentifiers(source: ts.SourceFile): Set<string> {
	const names = new Set<string>();
	const visit = (node: ts.Node): void => {
		if (ts.isIdentifier(node)) names.add(node.text);
		ts.forEachChild(node, visit);
	};
	visit(source);
	return names;
}

interface GeneratedImports {
	readonly module?: string;
	readonly localByImported: Map<string, string>;
}

function readGeneratedImports(source: ts.SourceFile): GeneratedImports {
	const localByImported = new Map<string, string>();
	let module: string | undefined;
	for (const statement of source.statements) {
		if (!ts.isImportDeclaration(statement)) continue;
		const specifier = statement.moduleSpecifier;
		if (!ts.isStringLiteral(specifier) || !generatedImportModule(specifier.text)) continue;
		module ??= specifier.text;
		const bindings = statement.importClause?.namedBindings;
		if (bindings === undefined || !ts.isNamedImports(bindings)) continue;
		for (const element of bindings.elements) {
			localByImported.set(element.propertyName?.text ?? element.name.text, element.name.text);
		}
	}
	return { module, localByImported };
}

function uniqueLocalName(base: string, taken: Set<string>): string {
	let candidate = base;
	let index = 2;
	while (taken.has(candidate)) {
		candidate = `${base}${index}`;
		index += 1;
	}
	taken.add(candidate);
	return candidate;
}

function lastImportPosition(source: ts.SourceFile): number {
	let position = 0;
	for (const statement of source.statements) {
		if (ts.isImportDeclaration(statement)) position = statement.getEnd();
	}
	return position;
}

function importEdit(source: ts.SourceFile, module: string, names: readonly { readonly imported: string; readonly local: string }[]): TextEdit {
	const lines = names.map(name => name.imported === name.local ? `\t${name.imported},` : `\t${name.imported} as ${name.local},`);
	const importText = [
		"// Generated implementation references: this import intentionally fails until these exports exist.",
		"import {",
		...lines,
		`} from ${JSON.stringify(module)};`,
	].join("\n");
	const position = lastImportPosition(source);
	if (position === 0) return { start: 0, end: 0, text: `${importText}\n\n` };
	return { start: position, end: position, text: `\n${importText}` };
}

function indentationBefore(text: string, position: number): string {
	const lineStart = text.lastIndexOf("\n", Math.max(0, position - 1)) + 1;
	const prefix = text.slice(lineStart, position);
	return /^[ \t]*$/.test(prefix) ? prefix : "";
}

function lastNonWhitespace(text: string, before: number): number {
	let index = before - 1;
	while (index >= 0 && /\s/.test(text[index])) index -= 1;
	return index;
}

function propertyInsertionEdits(
	text: string,
	object: ts.ObjectLiteralExpression,
	properties: readonly string[],
): TextEdit[] {
	if (properties.length === 0) return [];
	const closeBrace = object.getEnd() - 1;
	const closeLineStart = text.lastIndexOf("\n", closeBrace) + 1;
	const closePrefix = text.slice(closeLineStart, closeBrace);
	const closeOnOwnLine = closeLineStart > object.getStart() && /^[ \t]*$/.test(closePrefix);
	const objectIndent = indentationBefore(text, object.getStart());
	const firstProperty = object.properties[0];
	const propertyIndent = firstProperty === undefined
		? `${objectIndent}\t`
		: indentationBefore(text, firstProperty.getStart()) || `${objectIndent}\t`;
	const editedLines = properties.map(property => `${propertyIndent}${property}\n`);
	if (closeOnOwnLine) {
		const edits: TextEdit[] = [];
		const last = lastNonWhitespace(text, closeLineStart);
		if (last >= 0 && text[last] !== "," && text[last] !== "{") {
			edits.push({ start: last + 1, end: last + 1, text: "," });
		}
		edits.push({ start: closeLineStart, end: closeLineStart, text: editedLines.join("") });
		return edits;
	}
	const last = lastNonWhitespace(text, closeBrace);
	const separator = last >= 0 && text[last] !== "," && text[last] !== "{" ? ",\n" : "\n";
	return [{
		start: closeBrace,
		end: closeBrace,
		text: `${separator}${editedLines.join("")}${objectIndent}`,
	}];
}

function replacementEdit(entry: AdapterBindingEntry, localName: string): TextEdit | undefined {
	if (entry.value === undefined) return undefined;
	return { start: entry.value.getStart(), end: entry.value.getEnd(), text: localName };
}

function applyEdits(text: string, edits: readonly TextEdit[]): { text: string } | { conflict: true } {
	const sorted = [...edits].sort((left, right) => right.start - left.start || right.end - left.end);
	let result = text;
	let previousStart = Number.POSITIVE_INFINITY;
	for (const edit of sorted) {
		if (edit.end > previousStart) return { conflict: true };
		result = result.slice(0, edit.start) + edit.text + result.slice(edit.end);
		previousStart = edit.start;
	}
	return { text: result };
}

function memberEntry(inspection: AdapterInspection, member: string): AdapterBindingEntry | undefined {
	return inspection.bindings.get(member);
}

function buildSkeleton(
	inspection: AdapterInspection,
	adapter: string,
	targetMembers: ReadonlySet<string>,
): { content: string } | { error: string } {
	const port = inspection.port;
	if (port === undefined) return { error: "The canonical HarnessPort members could not be read; no skeleton can be generated." };
	const authoringSpecifier = moduleSpecifier(
		path.join(inspection.adapterDir, "port.ts"),
		path.join(inspection.root, "framework", "runtime", "adapter-authoring"),
	);
	const implementationSpecifier = "./missing-implementations";
	const imports: string[] = [];
	const entries: string[] = [];
	for (const member of port.members) {
		const referenced = !member.optional || targetMembers.has(member.name);
		if (!referenced) {
			entries.push(`\t${member.name}: unavailablePortMember(\n\t\t"this adapter has not supplied this optional capability yet; the framework uses its existing fallback",\n\t),`);
			continue;
		}
		const factoryName = factoryNameFor(member.name);
		imports.push(`\t${factoryName},`);
		entries.push(`\t${member.name}: ${factoryName},`);
	}
	const contextName = `${pascalCase(adapter)}PortContext`;
	const usesUnavailable = port.members.some(member => member.optional && !targetMembers.has(member.name));
	const authoringImports = usesUnavailable ? "defineAdapterPort, unavailablePortMember" : "defineAdapterPort";
	const lines = [
		GENERATED_HEADER,
		"// The imported implementation factories are intentionally absent: this assembly must not",
		"// compile until the real exports exist and construct these HarnessPort members.",
		`import { ${authoringImports} } from ${JSON.stringify(authoringSpecifier)};`,
		"import {",
		...imports,
		`} from ${JSON.stringify(implementationSpecifier)};`,
		"",
		"/**",
		" * The native host context this generated assembly still has to supply. It is an opaque",
		" * boundary, not a fabricated native implementation; replace or extend it with the host's real",
		" * context when the adapter implementation lands.",
		" */",
		`export interface ${contextName}<NativeHost = unknown> {`,
		"\treadonly nativeHost: NativeHost;",
		"}",
		"",
		`export const ${portConstantName(adapter)} = defineAdapterPort<${contextName}>({`,
		...entries,
		"});",
		"",
	];
	return { content: lines.join("\n") };
}

interface DeliveryGapWork {
	readonly contractId: string;
	readonly gaps: readonly DeliveryMemberGap[];
}

interface FilePlan {
	readonly source: ts.SourceFile;
	readonly original: string;
	readonly taken: Set<string>;
	readonly existingImports: GeneratedImports;
	readonly importModule: string;
	readonly newImports: Array<{ imported: string; local: string }>;
	readonly replacements: TextEdit[];
	readonly insertions: Map<ts.ObjectLiteralExpression, string[]>;
}

function existingGeneration(
	inspection: AdapterInspection,
	targets: ReadonlyMap<string, TargetMember>,
	deliveryGaps: readonly DeliveryGapWork[],
	diagnostics: IntegrationDiagnostic[],
	diagnosticKeys: Set<string>,
	root: string,
): { files: GeneratedFile[] } {
	const definition = inspection.definition;
	if (definition === undefined) return { files: [] };
	if (inspection.bindingsDynamic) {
		diagnosticAtAdapter(
			root,
			inspection.adapterDir,
			diagnostics,
			diagnosticKeys,
			"generate/dynamic-assembly",
			"The adapter bindings are composed dynamically, so adding missing factories is unsafe.",
			"Make the defineAdapterPort binding object a statically visible object literal, then rerun generation.",
		);
		return { files: [] };
	}
	const plans = new Map<string, FilePlan>();
	const planFor = (source: ts.SourceFile): FilePlan => {
		const key = path.resolve(source.fileName);
		const existing = plans.get(key);
		if (existing !== undefined) return existing;
		const existingImports = readGeneratedImports(source);
		const plan: FilePlan = {
			source,
			original: source.text,
			taken: collectIdentifiers(source),
			existingImports,
			importModule: existingImports.module ?? moduleSpecifier(
				source.fileName,
				path.join(inspection.adapterDir, "internal", MISSING_IMPLEMENTATION_MODULE),
			),
			newImports: [],
			replacements: [],
			insertions: new Map(),
		};
		plans.set(key, plan);
		return plan;
	};
	const addImport = (plan: FilePlan, imported: string): string => {
		const existingLocal = plan.existingImports.localByImported.get(imported);
		if (existingLocal !== undefined) return existingLocal;
		const local = uniqueLocalName(imported, plan.taken);
		plan.newImports.push({ imported, local });
		plan.existingImports.localByImported.set(imported, local);
		return local;
	};
	const addInsertion = (plan: FilePlan, object: ts.ObjectLiteralExpression, line: string): void => {
		const lines = plan.insertions.get(object) ?? [];
		if (!lines.includes(line)) lines.push(line);
		plan.insertions.set(object, lines);
	};

	for (const target of targets.values()) {
		const entry = memberEntry(inspection, target.member);
		if (entry?.status === "generated-missing") continue;
		const plan = planFor(definition.bindingsFile);
		const local = addImport(plan, factoryNameFor(target.member));
		if (target.replace) {
			if (entry === undefined) {
				diagnosticAtAdapter(
					root,
					inspection.adapterDir,
					diagnostics,
					diagnosticKeys,
					"generate/replacement",
					`The existing binding "${target.member}" disappeared between inspection and generation.`,
					"Re-run supply analysis and generation on the current source.",
				);
				continue;
			}
			const edit = replacementEdit(entry, local);
			if (edit === undefined) {
				diagnosticAtAdapter(
					root,
					inspection.adapterDir,
					diagnostics,
					diagnosticKeys,
					"generate/replacement",
					`The existing binding "${target.member}" cannot be replaced safely because its expression is not statically located.`,
					"Make the binding value an explicit unavailablePortMember(...) expression or omit the binding entirely.",
				);
				continue;
			}
			plan.replacements.push(edit);
		} else {
			addInsertion(plan, definition.bindings, `${target.member}: ${local},`);
		}
	}

	const contractAliases = new Map<string, string>();
	for (const work of deliveryGaps) {
		for (const gap of work.gaps) {
			if (gap.alreadyGenerated === true) continue;
			const plan = planFor(gap.payload.getSourceFile());
			const local = addImport(plan, deliveryExportName(gap));
			addInsertion(plan, gap.payload, `${gap.member}: ${local},`);
			contractAliases.set(deliveryContractName(gap), deliveryContractType(gap));
		}
	}
	if (diagnostics.length > 0) return { files: [] };

	const files: GeneratedFile[] = [];
	for (const plan of plans.values()) {
		const edits: TextEdit[] = [...plan.replacements];
		if (plan.newImports.length > 0) edits.push(importEdit(plan.source, plan.importModule, plan.newImports));
		for (const [object, lines] of plan.insertions) {
			edits.push(...propertyInsertionEdits(plan.original, object, lines));
		}
		if (edits.length === 0) continue;
		const applied = applyEdits(plan.original, edits);
		if ("conflict" in applied) {
			diagnosticAtAdapter(
				root,
				inspection.adapterDir,
				diagnostics,
				diagnosticKeys,
				"generate/edit-conflict",
				"The generated assembly edits overlap in the adapter source; nothing was written.",
				"Make the port binding object literal and the delivery construction conventional, then rerun generation.",
			);
			return { files: [] };
		}
		files.push({ file: relativeFile(root, plan.source.fileName), content: applied.text });
	}

	if (contractAliases.size > 0) {
		const contractFile = path.join(inspection.adapterDir, "internal", "missing-delivery-contracts.ts");
		const aliasLines = [...contractAliases].map(([name, type]) => `export type ${name} = ${type};`);
		let content: string;
		if (existsSync(contractFile)) {
			const current = readFileSync(contractFile, "utf8");
			if (!current.startsWith(GENERATED_HEADER)) {
				diagnosticAtAdapter(
					root,
					inspection.adapterDir,
					diagnostics,
					diagnosticKeys,
					"generate/contract-conflict",
					"The missing-delivery contract file already exists and was not generated by this tool.",
					"Move the existing contract file aside; no user-owned file was overwritten.",
				);
				return { files: [] };
			}
			const additions = aliasLines.filter(line => !current.includes(line));
			content = additions.length === 0
				? current
				: `${current}${current.endsWith("\n") ? "" : "\n"}${additions.join("\n")}\n`;
		} else {
			const authoringSpecifier = moduleSpecifier(
				contractFile,
				path.join(inspection.root, "framework", "runtime", "adapter-authoring"),
			);
			content = [
				GENERATED_HEADER,
				"// Missing delivery member types. Supply the corresponding exports in",
				"// internal/missing-implementations.ts; this file contains no implementation.",
				`import type { AdapterDeliveryMap } from ${JSON.stringify(authoringSpecifier)};`,
				"",
				...aliasLines,
				"",
			].join("\n");
		}
		files.push({ file: relativeFile(root, contractFile), content });
	}
	return { files };
}

