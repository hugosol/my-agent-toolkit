/** Generates missing assembly references; optional contracts are included only when requested. */
export function generateAdapter(options: GenerationOptions): GenerationResult {
	const root = path.resolve(options.root);
	const inspection = inspectAdapterSource(root, options.adapter);
	const diagnosticKeys = new Set<string>();
	const diagnostics: IntegrationDiagnostic[] = [];
	for (const item of [...options.supply.diagnostics, ...inspection.diagnostics]) {
		const key = `${item.code}|${item.file}|${item.line}|${item.column}|${item.message}`;
		if (diagnosticKeys.has(key)) continue;
		diagnosticKeys.add(key);
		diagnostics.push(item);
	}
	if (options.supply.adapter !== options.adapter) {
		diagnosticAtAdapter(
			root,
			inspection.adapterDir,
			diagnostics,
			diagnosticKeys,
			"generate/supply-adapter",
			`The supply result is for "${options.supply.adapter}", not "${options.adapter}".`,
			"Analyze supply for the adapter being generated.",
		);
	}
	const supplyById = new Map(options.supply.supplies.map(item => [item.contractId, item]));
	const targets = new Map<string, TargetMember>();
	const deliveryGaps: DeliveryGapWork[] = [];
	const generatedContracts: string[] = [];
	const generatedSeen = new Set<string>();
	let blocked = diagnostics.length > 0;

	const markGenerated = (contractId: string): void => {
		if (generatedSeen.has(contractId)) return;
		generatedSeen.add(contractId);
		generatedContracts.push(contractId);
	};

	const addTarget = (member: string): void => {
		if (inspection.port !== undefined && !inspection.port.byName.has(member)) {
			diagnosticAtAdapter(
				root,
				inspection.adapterDir,
				diagnostics,
				diagnosticKeys,
				"generate/unknown-member",
				`"${member}" is not a HarnessPort member, so no implementation reference can be generated.`,
				"Correct the demand contract instead of adding a non-contract binding.",
			);
			blocked = true;
			return;
		}
		const entry = memberEntry(inspection, member);
		const current = targets.get(member);
		targets.set(member, current ?? {
			member,
			replace: entry !== undefined && (entry.status === "unavailable" || entry.status === "undefined"),
		});
	};

	const works: ContractWork[] = [];
	for (const contract of options.contracts) {
		const supply = supplyById.get(contract.id);
		if (supply === undefined) {
			diagnosticAtAdapter(
				root,
				inspection.adapterDir,
				diagnostics,
				diagnosticKeys,
				"generate/missing-supply",
				`The supply result does not contain "${contract.id}".`,
				"Analyze supply for every demand contract before generating.",
			);
			blocked = true;
			continue;
		}
		const projection = contract.kind === "delivery" ? projectDeliveryContract(contract.id) : undefined;
		const projections = contract.kind === "framework" ? projectFrameworkContract(contract.id) : undefined;
		const portMember = contract.kind === "port"
			? contract.member
			: projection?.portMember ?? projections?.[0]?.portMember;
		works.push({
			contract,
			supply,
			...(portMember === undefined ? {} : { portMember }),
			...(projections === undefined ? {} : { projections }),
			include: contract.requirement === "required" || options.includeOptional === true,
		});
	}

	if (inspection.definition === undefined && inspection.files.length === 0) {
		const requiredPortMembers = new Set(inspection.port?.members.filter(member => !member.optional).map(member => member.name) ?? []);
		if (inspection.port === undefined) {
			diagnosticAtAdapter(
				root,
				inspection.adapterDir,
				diagnostics,
				diagnosticKeys,
				"generate/port-contract",
				"The canonical HarnessPort members could not be read; no complete adapter skeleton can be generated.",
				"Restore framework/runtime/port.ts and rerun generation.",
			);
			blocked = true;
		}
		for (const work of works) {
			if (!work.include) continue;
			if (work.contract.kind === "framework") {
				if (work.projections === undefined) {
					diagnosticAtAdapter(
						root,
						inspection.adapterDir,
						diagnostics,
						diagnosticKeys,
						"generate/unmapped-contract",
						`The framework semantic "${work.contract.id}" does not map to an adapter prerequisite.`,
						"Use a framework semantic ID with a declared adapter prerequisite.",
					);
					blocked = true;
					continue;
				}
				for (const projection of work.projections) requiredPortMembers.add(projection.portMember);
				markGenerated(work.contract.id);
				continue;
			}
			if (work.portMember === undefined) {
				diagnosticAtAdapter(
					root,
					inspection.adapterDir,
					diagnostics,
					diagnosticKeys,
					"generate/unmapped-contract",
					`The contract "${work.contract.id}" does not map to an adapter assembly member.`,
					"Use a port member or a delivery path the framework projects onto an adapter delivery.",
				);
				blocked = true;
				continue;
			}
			const portStatus = evaluatePortSupply(inspection, work.portMember);
			if (portStatus.status === "unresolved") {
				diagnosticAtAdapter(
					root,
					inspection.adapterDir,
					diagnostics,
					diagnosticKeys,
					"generate/unresolved-member",
					portStatus.reason ?? `The adapter member "${work.portMember}" cannot be resolved.`,
					"Correct the adapter source structure before generating.",
				);
				blocked = true;
				continue;
			}
			if (work.contract.requirement === "optional" && options.includeOptional !== true) continue;
			if (work.supply.status === "conditional" && work.contract.requirement === "required") {
				diagnosticAtAdapter(
					root,
					inspection.adapterDir,
					diagnostics,
					diagnosticKeys,
					"generate/conditional-required",
					`The required contract "${work.contract.id}" is only conditionally available; generation does not replace a conditional factory.`,
					"Resolve the runtime condition explicitly in the adapter assembly, then rerun generation.",
				);
				blocked = true;
				continue;
			}
			if (work.supply.status === "unresolved") {
				diagnosticAtAdapter(
					root,
					inspection.adapterDir,
					diagnostics,
					diagnosticKeys,
					"generate/unresolved-contract",
					work.supply.reason ?? `The contract "${work.contract.id}" could not be resolved.`,
					"Make the adapter assembly expression statically explicit before generating.",
				);
				blocked = true;
				continue;
			}
			requiredPortMembers.add(work.portMember);
			markGenerated(work.contract.id);
		}
		if (blocked) return { adapter: options.adapter, files: [], generatedContracts: [], diagnostics };
		const skeleton = buildSkeleton(inspection, path.basename(inspection.adapterDir), requiredPortMembers);
		if ("error" in skeleton) {
			diagnosticAtAdapter(root, inspection.adapterDir, diagnostics, diagnosticKeys, "generate/skeleton", skeleton.error, "Restore the canonical framework contract and rerun generation.");
			return { adapter: options.adapter, files: [], generatedContracts: [], diagnostics };
		}
		const targetFile = path.join(inspection.adapterDir, "port.ts");
		if (existsSync(targetFile)) {
			const current = readFileSync(targetFile, "utf8");
			if (!current.startsWith(GENERATED_HEADER)) {
				diagnosticAtAdapter(
					root,
					inspection.adapterDir,
					diagnostics,
					diagnosticKeys,
					"generate/conflict",
					"The complete adapter skeleton target already exists and was not generated by this tool.",
					"Move the existing file aside or choose another adapter name; no user-owned file was overwritten.",
				);
				return { adapter: options.adapter, files: [], generatedContracts: [], diagnostics };
			}
			if (current === skeleton.content) {
				return { adapter: options.adapter, files: [{ file: relativeFile(root, targetFile), content: skeleton.content }], generatedContracts, diagnostics };
			}
		}
		const file: GeneratedFile = { file: relativeFile(root, targetFile), content: skeleton.content };
		if (options.dryRun !== true) {
			mkdirSync(path.dirname(targetFile), { recursive: true });
			writeFileSync(targetFile, skeleton.content, "utf8");
		}
		return { adapter: options.adapter, files: [file], generatedContracts, diagnostics };
	}

	if (!inspection.exists) {
		// An absent adapter with no canonical framework contract is handled above; this branch keeps
		// an explicit diagnostic instead of silently generating an arbitrary file.
		diagnosticAtAdapter(
			root,
			inspection.adapterDir,
			diagnostics,
			diagnosticKeys,
			"generate/absent",
			`The adapter "${options.adapter}" does not exist and its framework contract could not be read.`,
			"Run generation from a root containing framework/runtime/port.ts.",
		);
		return { adapter: options.adapter, files: [], generatedContracts: [], diagnostics };
	}

	if (inspection.definition === undefined) {
		if (inspection.files.length > 0) {
			diagnosticAtAdapter(
				root,
				inspection.adapterDir,
				diagnostics,
				diagnosticKeys,
				"generate/unrecognized-adapter",
				"The adapter contains source but no inspectable defineAdapterPort assembly; no file was edited.",
				"Convert its port to defineAdapterPort<Context>({...}) or create the missing assembly explicitly.",
			);
		}
		return { adapter: options.adapter, files: [], generatedContracts: [], diagnostics };
	}

	for (const work of works) {
		if (!work.include) continue;
		if (work.contract.kind === "framework") {
			if (work.supply.status === "provided") continue;
			if (work.supply.status === "conditional") {
				if (work.contract.requirement === "required") {
					diagnosticAtAdapter(
						root,
						inspection.adapterDir,
						diagnostics,
						diagnosticKeys,
						"generate/conditional-required",
						`The required framework semantic "${work.contract.id}" is only conditionally available.`,
						"Resolve the runtime condition explicitly in the adapter assembly, then rerun generation.",
					);
					blocked = true;
				}
				continue;
			}
			if (work.supply.status === "unresolved") {
				diagnosticAtAdapter(
					root,
					inspection.adapterDir,
					diagnostics,
					diagnosticKeys,
					"generate/unresolved-contract",
					work.supply.reason ?? `The framework semantic "${work.contract.id}" could not be resolved.`,
					"Make the adapter assembly expression statically explicit before generating.",
				);
				blocked = true;
				continue;
			}
			const projections = work.projections;
			if (projections === undefined) {
				diagnosticAtAdapter(
					root,
					inspection.adapterDir,
					diagnostics,
					diagnosticKeys,
					"generate/unmapped-contract",
					`The framework semantic "${work.contract.id}" does not map to an adapter prerequisite.`,
					"Use a framework semantic ID with a declared adapter prerequisite.",
				);
				blocked = true;
				continue;
			}
			let generated = false;
			let blockedProjection: string | undefined;
			let conditionalProjection: string | undefined;
			let unresolvedProjection: string | undefined;
			for (const projection of projections) {
				const entry = memberEntry(inspection, projection.portMember);
				if (entry?.status === "generated-missing") {
					generated = true;
					break;
				}
				const portStatus = evaluatePortSupply(inspection, projection.portMember);
				if (portStatus.status === "missing" || portStatus.status === "unavailable") {
					if (entry === undefined || entry.status === "unavailable" || entry.status === "undefined") {
						addTarget(projection.portMember);
						generated = true;
						break;
					}
					blockedProjection ??= projection.portMember;
				} else if (portStatus.status === "provided") {
					blockedProjection ??= projection.portMember;
				} else if (portStatus.status === "conditional") {
					conditionalProjection ??= projection.portMember;
				} else {
					unresolvedProjection ??= projection.portMember;
				}
			}
			if (generated) {
				markGenerated(work.contract.id);
				continue;
			}
			if (blockedProjection !== undefined) {
				diagnosticAtAdapter(
					root,
					inspection.adapterDir,
					diagnostics,
					diagnosticKeys,
					"generate/unsupported-framework",
					`The framework semantic "${work.contract.id}" is missing inside the existing "${blockedProjection}" implementation, whose native wiring cannot be rewritten safely.`,
					"Add the required delivery construction or member in the existing implementation factory; generation will not rewrite native wiring.",
				);
				blocked = true;
			} else if (unresolvedProjection !== undefined) {
				diagnosticAtAdapter(
					root,
					inspection.adapterDir,
					diagnostics,
					diagnosticKeys,
					"generate/unresolved-member",
					`The adapter prerequisite "${unresolvedProjection}" for "${work.contract.id}" could not be resolved.`,
					"Correct the adapter assembly before adding a missing implementation reference.",
				);
				blocked = true;
			} else if (conditionalProjection !== undefined) {
				diagnosticAtAdapter(
					root,
					inspection.adapterDir,
					diagnostics,
					diagnosticKeys,
					"generate/conditional-required",
					`The adapter prerequisite "${conditionalProjection}" for "${work.contract.id}" is conditional.`,
					"Resolve the condition explicitly before regenerating.",
				);
				blocked = true;
			} else {
				diagnosticAtAdapter(
					root,
					inspection.adapterDir,
					diagnostics,
					diagnosticKeys,
					"generate/unresolved-framework",
					`No adapter prerequisite for "${work.contract.id}" can be generated.`,
					"Review the framework semantic and its adapter route.",
				);
				blocked = true;
			}
			continue;
		}
		const member = work.portMember;
		if (member === undefined) {
			diagnosticAtAdapter(
				root,
				inspection.adapterDir,
				diagnostics,
				diagnosticKeys,
				"generate/unmapped-contract",
				`The contract "${work.contract.id}" does not map to an adapter assembly member.`,
				"Use a port member or a delivery path the framework projects onto an adapter delivery.",
			);
			blocked = true;
			continue;
		}
		const entry = memberEntry(inspection, member);
		if (entry?.status === "generated-missing") {
			markGenerated(work.contract.id);
			continue;
		}
		if (work.supply.status === "provided") continue;
		if (work.supply.status === "conditional") {
			if (work.contract.requirement === "required") {
				diagnosticAtAdapter(
					root,
					inspection.adapterDir,
					diagnostics,
					diagnosticKeys,
					"generate/conditional-required",
					`The required contract "${work.contract.id}" is only conditionally available; generation does not replace a conditional factory.`,
					"Resolve the runtime condition explicitly in the adapter assembly, then rerun generation.",
				);
				blocked = true;
			}
			continue;
		}
		if (work.supply.status === "unresolved") {
			diagnosticAtAdapter(
				root,
				inspection.adapterDir,
				diagnostics,
				diagnosticKeys,
				"generate/unresolved-contract",
				work.supply.reason ?? `The contract "${work.contract.id}" could not be resolved.`,
				"Make the adapter assembly expression statically explicit before generating.",
			);
			blocked = true;
			continue;
		}
		const portStatus = evaluatePortSupply(inspection, member);
		if (portStatus.status === "provided") {
			if (work.contract.kind === "delivery" || work.contract.kind === "port") {
				const projection = work.contract.kind === "delivery"
					? projectDeliveryContract(work.contract.id)
					: projectPortDelivery(inspection, member);
				const gapInspection = projection === undefined
					? { gaps: [], reason: "The delivery path does not project onto an adapter delivery." }
					: inspectDeliveryMemberGaps(inspection, projection);
				if (gapInspection.gaps.length > 0 && gapInspection.reason === undefined) {
					deliveryGaps.push({ contractId: work.contract.id, gaps: gapInspection.gaps });
					markGenerated(work.contract.id);
					continue;
				}
				diagnosticAtAdapter(
					root,
					inspection.adapterDir,
					diagnostics,
					diagnosticKeys,
					"generate/unsupported-delivery",
					`The delivery contract "${work.contract.id}" is missing inside the existing "${member}" implementation: ${gapInspection.reason ?? "no concrete payload property can be added safely"}.`,
					"Add the reachable defineAdapterDelivery construction and demanded member explicitly, then rerun generation.",
				);
			} else {
				diagnosticAtAdapter(
					root,
					inspection.adapterDir,
					diagnostics,
					diagnosticKeys,
					"generate/inconsistent-supply",
					`The port is analyzed as provided but the contract "${work.contract.id}" is not.`,
					"Re-run supply analysis; do not generate over an inconsistent analysis.",
				);
			}
			blocked = true;
			continue;
		}
		if (portStatus.status === "conditional" || portStatus.status === "unresolved") {
			diagnosticAtAdapter(
				root,
				inspection.adapterDir,
				diagnostics,
				diagnosticKeys,
				portStatus.status === "conditional" ? "generate/conditional-required" : "generate/unresolved-member",
				portStatus.reason ?? `The adapter member "${member}" cannot be resolved for generation.`,
				portStatus.status === "conditional"
					? "Resolve the conditional factory only if the runtime condition is understood."
					: "Correct the adapter assembly before adding a missing implementation reference.",
			);
			blocked = true;
			continue;
		}
		if (work.supply.status !== "missing" && work.supply.status !== "unavailable") continue;
		if (entry === undefined || entry.status === "unavailable" || entry.status === "undefined") {
			addTarget(member);
			markGenerated(work.contract.id);
			continue;
		}
		diagnosticAtAdapter(
			root,
			inspection.adapterDir,
			diagnostics,
			diagnosticKeys,
			"generate/unsupported-binding",
			`The binding for "${member}" exists in a form generation cannot safely replace.`,
			"Make the binding an explicit factory or an unavailablePortMember(...) before generating.",
		);
		blocked = true;
	}

	if (blocked) return { adapter: options.adapter, files: [], generatedContracts: [], diagnostics };
	const generation = existingGeneration(inspection, targets, deliveryGaps, diagnostics, diagnosticKeys, root);
	const files = diagnostics.length > 0 ? [] : generation.files;
	if (options.dryRun !== true) {
		for (const file of files) writeFileSync(path.resolve(root, file.file), file.content, "utf8");
	}
	return {
		adapter: options.adapter,
		files,
		generatedContracts: diagnostics.length === 0 ? generatedContracts : [],
		diagnostics,
	};
}
